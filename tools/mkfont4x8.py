def row_byte(row):
    n = 0
    for i, c in enumerate(row):
        if c == "#":
            n |= 0x8 >> i
    return (n << 4) | n


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "font4x8.h"
    missing = [chr(c) for c in range(32, 128) if chr(c) not in G]
    if missing:
        sys.exit("missing glyphs: %r" % missing)
    lines = ["/* generated by tools/mkfont4x8.py - do not edit */",
             "#ifndef FONT4X8_H", "#define FONT4X8_H", "",
             "/* ASCII 32..127, 8 bytes per glyph, pattern duplicated in both nybbles */",
             "static const char font4x8[96 * 8] = {"]
    for c in range(32, 128):
        bs = ", ".join("0x%02x" % row_byte(r) for r in G[chr(c)])
        label = chr(c) if chr(c) not in "\\\x7f" else ("backslash" if c == 92 else "block")
        lines.append("\t%s,\t/* %3d %s */" % (bs, c, label.replace("*/", "* /")))
    lines += ["};", "", "#endif", ""]
    with open(out, "w") as f:
        f.write("\n".join(lines))
    print("wrote", out)


if __name__ == "__main__":
    main()
