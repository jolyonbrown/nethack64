"""
mkfont4x8.py - generate the 4x8 font used by the software 80-column screen.

Each glyph is drawn below as 8 rows of 4 characters ('#' = pixel set).
Column 3 is normally left blank for inter-character spacing; glyphs that
must join their neighbours (the NetHack wall '-' and the box-drawing
style '|' that fills the full cell height) use all four columns / rows.

Output: a C header with `static const char font4x8[96 * 8]` covering ASCII
32..127.  Each byte holds the 4-bit row pattern duplicated in both nybbles
(e.g. pattern 0110 -> 0x66) so the renderer can combine a left and right
character with a single AND/OR per row, without shifting:

    bitmap_byte = (glyph_left[row] & 0xF0) | (glyph_right[row] & 0x0F)

The font is original to this project (CC0) and is deliberately plain; tune
glyphs here and re-run `make font`.

Usage: mkfont4x8.py out.h
"""
import sys

# rows 0..7; unspecified rows are blank.  Caps/digits sit on rows 1-5,
# lowercase x-height is rows 3-5, ascenders rows 1-2, descenders rows 6-7.
G = {}


def g(ch, **rows):
    bitmap = ["...."] * 8
    for k, v in rows.items():
        r = int(k[1:])
        bitmap[r] = (v + "....")[:4]
    G[ch] = bitmap


